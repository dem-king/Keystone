/* ============================================================
   时段问候：工作台与登录开屏共用同一规则，不各自维护一份。
   ============================================================ */

/** 按当前时段返回问候语：夜深了 / 上午好 / 中午好 / 下午好 / 晚上好 */
export function greetingOf(date: Date = new Date()) {
  const h = date.getHours()
  return h < 6 ? '夜深了' : h < 12 ? '上午好' : h < 14 ? '中午好' : h < 18 ? '下午好' : '晚上好'
}
